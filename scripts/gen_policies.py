#!/usr/bin/env python3
"""Generate the vault-posture read-only policies (task policies). Never edit the .hcl files by hand.

Namespace-local rules repeat once per nesting level ("+" = one namespace segment): a token
created in the root namespace is checked against "<ns path>/<request path>" for requests
made inside a child namespace. tests/test_policy.py fails if the committed files drift.
"""

import sys
from pathlib import Path

POLICY_DIR = Path(__file__).resolve().parents[1] / "skills/vault-posture/policies"
LEVELS = 6  # root + MAX_NAMESPACE_DEPTH (5) levels, as in vault_posture.py

BASE_HEADER = """\
# vault-posture-readonly: the base policy the vault-posture skill's token needs.
# GENERATED by scripts/gen_policies.py (task policies): do not edit by hand.
#
# Grants read/list on exactly the endpoints vault_posture.py reads for audit, quotas,
# security and roles. PKI reads are in the opt-in add-on vault-posture-pki-reader.
# Load once in the ROOT namespace and mint a short-lived token per session:
#   vault policy write vault-posture-readonly vault-posture-readonly.hcl
#   vault token create -policy=vault-posture-readonly -no-default-policy -orphan -ttl=1h
#
# Namespace-local rules repeat for the root namespace and five nesting levels.
"""

PKI_HEADER = """\
# vault-posture-pki-reader: opt-in add-on for the vault-posture `pki` subcommand (and the
# PKI part of `audit`). GENERATED by scripts/gen_policies.py (task policies): do not edit.
#
# PKI mounts can have any name, so these grants use "+" for the mount: on a KV v1 mount they
# would also expose secrets stored at <mount>/issuer/<x> or <mount>/config/{crl,urls,auto-tidy}.
# That is why they are not in the base policy. Attach alongside vault-posture-readonly:
#   vault policy write vault-posture-pki-reader vault-posture-pki-reader.hcl
#   vault token create -policy=vault-posture-readonly -policy=vault-posture-pki-reader -no-default-policy -orphan -ttl=1h
#
# Namespace-local rules repeat for the root namespace and five nesting levels.
"""

# Root namespace only: cluster-wide endpoints.
ROOT_RULES = [
    ("Token validation (the script calls lookup-self before any other read)", "auth/token/lookup-self", ["read"]),
    ("Quotas", "sys/quotas/config", ["read"]),
    (None, "sys/quotas/rate-limit/*", ["read", "list"]),
    ("Enterprise only; Community answers 404 and the scope is reported as unsupported", "sys/quotas/lease-count/*", ["read", "list"]),
    ("Seal-key operation status (the script keeps started/progress/required only)", "sys/generate-root/attempt", ["read"]),
    (None, "sys/generate-recovery-token/attempt", ["read"]),
    (None, "sys/rekey/init", ["read"]),
    (None, "sys/rekey-recovery-key/init", ["read"]),
    ("Barrier key and plugins", "sys/key-status", ["read"]),
    (None, "sys/rotate/config", ["read"]),
    (None, "sys/plugins/catalog", ["read"]),
]

# Per namespace level.
NAMESPACE_RULES = [
    ("Namespace discovery", "sys/namespaces/", ["list"]),
    ("Auth mounts and roles: JWT/OIDC, Kubernetes, AppRole (role/<name> only: never role-id or secret-id)", "sys/auth", ["read"]),
    (None, "auth/+/role/", ["list"]),
    (None, "auth/+/role/+", ["read"]),
    ("Token roles", "auth/token/roles/", ["list"]),
    (None, "auth/token/roles/+", ["read"]),
]

PKI_RULES = [
    ("Mount discovery (finds mounts of type pki)", "sys/mounts", ["read"]),
    ("Issuers: the script parses the public certificate and never stores the PEM", "+/issuers/", ["list"]),
    (None, "+/issuer/+", ["read"]),
    ("Mount configuration", "+/config/auto-tidy", ["read"]),
    (None, "+/config/crl", ["read"]),
    (None, "+/config/urls", ["read"]),
]

# Defence in depth for when this policy is attached next to broader ones.
DENY_RULES = [
    "+/creds/*",
    "+/issue/*",
    "+/sign/*",
    "sys/wrapping/unwrap",
    "sys/generate-root/update",
    "sys/rekey/update",
    "auth/+/role/+/role-id",
    "auth/+/role/+/secret-id",
    "auth/+/role/+/secret-id/*",
    "auth/+/role/+/secret-id-accessor/*",
]


def block(path: str, caps: list[str]) -> str:
    quoted = ", ".join(f'"{c}"' for c in caps)
    return f'path "{path}" {{\n  capabilities = [{quoted}]\n}}\n'


def section(title: str, rules: list, levels: int) -> str:
    out = [f"\n# ---- {title}\n"]
    for comment, path, caps in rules:
        if comment:
            out.append(f"\n# {comment}\n")
        for level in range(levels):
            if path == "sys/namespaces/" and level == levels - 1:
                continue  # the deepest level has no children to discover
            out.append(block("+/" * level + path, caps))
    return "".join(out)


def base_policy() -> str:
    text = BASE_HEADER + section("root namespace (cluster-wide)", ROOT_RULES, 1) + section("every namespace level", NAMESPACE_RULES, LEVELS)
    text += "\n# ---- defence in depth: credential-minting, token-consuming and AppRole secret endpoints\n"
    return text + "".join(block(p, ["deny"]) for p in DENY_RULES)


def pki_policy() -> str:
    return PKI_HEADER + section("every namespace level", PKI_RULES, LEVELS)


def rendered() -> dict[Path, str]:
    return {POLICY_DIR / "vault-posture-readonly.hcl": base_policy(), POLICY_DIR / "vault-posture-pki-reader.hcl": pki_policy()}


def main() -> int:
    for path, text in rendered().items():
        path.write_text(text)
        print(f"wrote {path.relative_to(Path.cwd()) if path.is_relative_to(Path.cwd()) else path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
